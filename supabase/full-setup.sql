-- When an order becomes completed, deduct recipe ingredients once (legacy kk_kitchen_deduct_inventory_for_order).
create or replace function public.kitchen_deduct_on_complete ()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  ing record;
begin
  if new.order_status = 'completed' and old.order_status is distinct from 'completed'
     and not exists (
       select 1 from public.kitchen_inventory_moves m
        where m.order_id = new.id and m.reason = 'recipe_deduct'
     ) then
    for ing in
      select ri.inventory_id, ri.quantity * oi.quantity as qty
        from public.order_items oi
        join public.kitchen_recipes r on r.menu_id = oi.menu_id
        join public.kitchen_recipe_ingredients ri on ri.recipe_id = r.id
        join public.kitchen_inventory i on i.id = ri.inventory_id and i.shop_id = new.shop_id
       where oi.order_id = new.id
    loop
      perform public.kitchen_adjust_stock(ing.inventory_id, new.shop_id, -ing.qty, 'recipe_deduct', new.id, 'Order #' || new.id);
    end loop;
  end if;
  return new;
end;
$$;

drop trigger if exists kitchen_deduct_on_complete on public.orders;
create trigger kitchen_deduct_on_complete
  after update of order_status on public.orders
  for each row
  execute function public.kitchen_deduct_on_complete ();
