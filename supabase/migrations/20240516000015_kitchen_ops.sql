-- Kitchen operations (ports legacy app/kitchen_ops.php): inventory, stock moves,
-- recipes + ingredients, waste log, purchase orders, and automatic recipe-based
-- stock deduction when an order is completed. Safe to re-run.
--
-- The Next.js staff pages read/write these tables with the service role after
-- checking the staff member's shop, so RLS is enabled with no client policies.

create table if not exists public.kitchen_inventory (
  id bigint generated by default as identity primary key,
  shop_id bigint not null references public.restaurants (id) on delete cascade,
  sku text not null,
  name text not null,
  unit text not null default 'pcs',
  qty_on_hand numeric(12, 3) not null default 0,
  reorder_level numeric(12, 3) not null default 0,
  cost_per_unit numeric(10, 2) not null default 0,
  supplier_name text,
  updated_at timestamptz not null default now(),
  unique (shop_id, sku)
);

create table if not exists public.kitchen_inventory_moves (
  id bigint generated by default as identity primary key,
  inventory_id bigint not null references public.kitchen_inventory (id) on delete cascade,
  shop_id bigint not null references public.restaurants (id) on delete cascade,
  delta_qty numeric(12, 3) not null,
  reason text not null check (reason in ('sale', 'adjustment', 'waste', 'receive', 'recipe_deduct')),
  order_id bigint references public.orders (id) on delete set null,
  user_id uuid references auth.users (id) on delete set null,
  note text,
  created_at timestamptz not null default now()
);
create index if not exists kitchen_inventory_moves_shop_idx on public.kitchen_inventory_moves (shop_id, created_at desc);

create table if not exists public.kitchen_recipes (
  id bigint generated by default as identity primary key,
  shop_id bigint not null references public.restaurants (id) on delete cascade,
  menu_id bigint not null unique references public.menus (id) on delete cascade,
  yield_servings int not null default 1,
  prep_minutes int not null default 15,
  steps text,
  calories int,
  allergens text,
  protein_g numeric(6, 1),
  carbs_g numeric(6, 1),
  fat_g numeric(6, 1),
  updated_at timestamptz not null default now()
);

create table if not exists public.kitchen_recipe_ingredients (
  id bigint generated by default as identity primary key,
  recipe_id bigint not null references public.kitchen_recipes (id) on delete cascade,
  inventory_id bigint not null references public.kitchen_inventory (id) on delete cascade,
  quantity numeric(12, 3) not null check (quantity > 0)
);
create index if not exists kitchen_recipe_ingredients_recipe_idx on public.kitchen_recipe_ingredients (recipe_id);

create table if not exists public.kitchen_waste_logs (
  id bigint generated by default as identity primary key,
  shop_id bigint not null references public.restaurants (id) on delete cascade,
  inventory_id bigint not null references public.kitchen_inventory (id) on delete cascade,
  qty numeric(12, 3) not null,
  reason text not null,
  cost_impact numeric(10, 2) not null default 0,
  logged_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists kitchen_waste_logs_shop_idx on public.kitchen_waste_logs (shop_id, created_at desc);

create table if not exists public.kitchen_purchase_orders (
  id bigint generated by default as identity primary key,
  shop_id bigint not null references public.restaurants (id) on delete cascade,
  po_number text not null unique,
  supplier_name text not null,
  status text not null default 'draft' check (status in ('draft', 'sent', 'received', 'cancelled')),
  notes text,
  created_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.kitchen_purchase_order_items (
  id bigint generated by default as identity primary key,
  po_id bigint not null references public.kitchen_purchase_orders (id) on delete cascade,
  inventory_id bigint not null references public.kitchen_inventory (id) on delete cascade,
  qty_ordered numeric(12, 3) not null,
  qty_received numeric(12, 3) not null default 0,
  unit_cost numeric(10, 2) not null default 0
);

alter table public.kitchen_inventory enable row level security;
alter table public.kitchen_inventory_moves enable row level security;
alter table public.kitchen_recipes enable row level security;
alter table public.kitchen_recipe_ingredients enable row level security;
alter table public.kitchen_waste_logs enable row level security;
alter table public.kitchen_purchase_orders enable row level security;
alter table public.kitchen_purchase_order_items enable row level security;

-- Atomic stock change + audit row (legacy kk_kitchen_adjust_stock).
create or replace function public.kitchen_adjust_stock (
  p_inventory_id bigint,
  p_shop_id bigint,
  p_delta numeric,
  p_reason text,
  p_order_id bigint default null,
  p_note text default null,
  p_user_id uuid default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.kitchen_inventory
     set qty_on_hand = qty_on_hand + p_delta, updated_at = now()
   where id = p_inventory_id and shop_id = p_shop_id;
  if not found then
    raise exception 'Inventory item % not found for shop %', p_inventory_id, p_shop_id;
  end if;
  insert into public.kitchen_inventory_moves (inventory_id, shop_id, delta_qty, reason, order_id, user_id, note)
  values (p_inventory_id, p_shop_id, p_delta, p_reason, p_order_id, p_user_id, p_note);
end;
$$;

revoke all on function public.kitchen_adjust_stock (bigint, bigint, numeric, text, bigint, text, uuid) from public, anon, authenticated;
grant execute on function public.kitchen_adjust_stock (bigint, bigint, numeric, text, bigint, text, uuid) to service_role;

-- When an order becomes completed, deduct recipe ingredients once (legacy kk_kitchen_deduct_inventory_for_order).
create or replace function public.kitchen_deduct_on_complete ()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  ing record;
begin
  if new.order_status = 'completed' and old.order_status is distinct from 'completed'
     and not exists (
       select 1 from public.kitchen_inventory_moves m
        where m.order_id = new.id and m.reason = 'recipe_deduct'
     ) then
    for ing in
      select ri.inventory_id, ri.quantity * oi.quantity as qty
        from public.order_items oi
        join public.kitchen_recipes r on r.menu_id = oi.menu_id
        join public.kitchen_recipe_ingredients ri on ri.recipe_id = r.id
        join public.kitchen_inventory i on i.id = ri.inventory_id and i.shop_id = new.shop_id
       where oi.order_id = new.id
    loop
      perform public.kitchen_adjust_stock(ing.inventory_id, new.shop_id, -ing.qty, 'recipe_deduct', new.id, 'Order #' || new.id);
    end loop;
  end if;
  return new;
end;
$$;

drop trigger if exists kitchen_deduct_on_complete on public.orders;
create trigger kitchen_deduct_on_complete
  after update of order_status on public.orders
  for each row
  execute function public.kitchen_deduct_on_complete ();
