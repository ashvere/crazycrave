-- Rider <-> admin (dispatch) messaging: one thread per rider. Safe to re-run.
-- Messages are written by server code (service role) after checking who is
-- sending; signed-in riders and admins may read their threads for live polling.

create table if not exists public.rider_staff_messages (
  id bigint generated by default as identity primary key,
  rider_id uuid not null references auth.users (id) on delete cascade,
  sender_user_id uuid references auth.users (id) on delete set null,
  sender_role text not null check (sender_role in ('staff', 'rider')),
  body text not null check (char_length(body) between 1 and 1000),
  created_at timestamptz not null default now(),
  read_at_rider timestamptz,
  read_at_staff timestamptz
);

create index if not exists rider_staff_messages_thread_idx on public.rider_staff_messages (rider_id, id);

alter table public.rider_staff_messages enable row level security;

drop policy if exists "rider_staff_messages_rider_select" on public.rider_staff_messages;
drop policy if exists "rider_staff_messages_admin_select" on public.rider_staff_messages;

create policy "rider_staff_messages_rider_select"
  on public.rider_staff_messages
  for select
  to authenticated
  using (rider_id = auth.uid());

create policy "rider_staff_messages_admin_select"
  on public.rider_staff_messages
  for select
  to authenticated
  using (public.auth_profile_role() = 'admin');

grant select on public.rider_staff_messages to authenticated;
